-- ==============================================================================
-- 风控三项筛选_Superset生产环境SQL模板.sql
-- ==============================================================================
-- 【设计原则】不对3-5亿行数据做"随机抽样再筛选"，而是把GROUP BY+HAVING
-- 这类聚合筛选逻辑直接下推到StarRocks数据库引擎执行——数据库的列式存储
-- 和向量化执行引擎，对这种大规模聚合的效率远高于把数据搬出来在客户端算。
-- 三条需求分别对应下面三段SQL，可以直接在Superset的SQL Lab里粘贴执行。
-- ==============================================================================

-- ------------------------------------------------------------------
-- 需求一：策略性风控 —— 每局第50把及之后才投注，且晚注比例≥70%，订单数>100
-- ------------------------------------------------------------------
SELECT
    bet05 AS uid,                                  -- 会员活动ID
    ROUND(AVG(CASE WHEN bet04 >= 50 THEN 1.0 ELSE 0.0 END), 4) AS 投注比例,
        -- 用AVG(CASE WHEN...)算比例，是SQL里最标准的"条件占比"写法，
        -- 比先COUNT两次再相除更省一次全表扫描
    SUM(CASE WHEN bet04 >= 50 THEN 1 ELSE 0 END) AS 订单数
        -- 只统计满足"第50把及以后"这个条件的订单数，不是全部订单数
FROM ods_a168_bet01
GROUP BY bet05                                     -- 按会员分组聚合，这一步是StarRocks最擅长的向量化聚合
HAVING COUNT(*) > 100                              -- 总订单数(不分是否晚注)必须超过100笔才纳入
   AND AVG(CASE WHEN bet04 >= 50 THEN 1.0 ELSE 0.0 END) >= 0.70
ORDER BY 投注比例 DESC;


-- ------------------------------------------------------------------
-- 需求二：团伙同桌风控 —— 同桌率≥30%，同桌订单数>100
-- ------------------------------------------------------------------
-- 【性能提示】这是自连接(self-join)，3-5亿行做自连接的计算量会随行数
-- 平方级增长，务必先用WHERE子句把日期范围/游戏类型缩小到合理区间，
-- 再执行下面这段，否则单次查询可能占满整个集群资源。
WITH 同局配对 AS (
    SELECT
        a.bet05 AS uid1,
        b.bet05 AS uid2,
        a.bet03                                    -- 局/靴ID，同一局出现的两个不同会员才算一次"同桌"
    FROM ods_a168_bet01 a
    JOIN ods_a168_bet01 b
      ON a.bet03 = b.bet03                         -- 同一局
     AND a.bet05 < b.bet05                          -- 只保留uid1<uid2，避免(A,B)/(B,A)重复计两次
    -- WHERE a.dt >= '2026-01-01'                   -- 生产环境务必加日期范围限制，控制自连接规模
),
同桌统计 AS (
    SELECT uid1, uid2, COUNT(DISTINCT bet03) AS 同桌局数
    FROM 同局配对
    GROUP BY uid1, uid2
),
各自总局数 AS (
    SELECT bet05 AS uid, COUNT(DISTINCT bet03) AS 总局数
    FROM ods_a168_bet01
    GROUP BY bet05
)
SELECT
    s.uid1, s.uid2, s.同桌局数,
    ROUND(s.同桌局数 * 1.0 / LEAST(t1.总局数, t2.总局数), 4) AS 同桌率
        -- 分母用两人中较小的总局数(保守定义)，避免"超活跃玩家跟很多人
        -- 都同桌一两次"被误判成"同桌率很高"这种假阳性
FROM 同桌统计 s
JOIN 各自总局数 t1 ON s.uid1 = t1.uid
JOIN 各自总局数 t2 ON s.uid2 = t2.uid
WHERE s.同桌局数 > 100
  AND s.同桌局数 * 1.0 / LEAST(t1.总局数, t2.总局数) >= 0.30
ORDER BY 同桌率 DESC;


