# ==============================================================================
# 合并五批同桌配对数据.R
# ==============================================================================
# 用途：把Superset分5批下载的同桌配对CSV，在本地合并、跨批次累加同桌局数、
# 做最终的>50局筛选——这一步必须在本地做，不能在StarRocks每批各自筛完，
# 否则会漏掉"分散在多个月、每月没到50但累计过线"的真实团伙。
# ==============================================================================

library(data.table)

# 请把下面路径改成您本地实际存放这五份CSV的文件夹
数据文件夹 <- "数据库_v2_候选名单版"

# 逐批读取（每一行代码读一批，用途都标清楚）
批1 <- fread(file.path(数据文件夹, "同桌配对_批1_0321-0331.csv"))  # 3月21-31日，11天
批2 <- fread(file.path(数据文件夹, "同桌配对_批2_0401-0430.csv"))  # 4月整月
批3 <- fread(file.path(数据文件夹, "同桌配对_批3_0501-0531.csv"))  # 5月整月
批4 <- fread(file.path(数据文件夹, "同桌配对_批4_0601-0630.csv"))  # 6月整月
批5 <- fread(file.path(数据文件夹, "同桌配对_批5_0701-0724.csv"))  # 7月1-24日

# 合并五批为一张长表（rbindlist比rbind快很多，适合这种批量合并场景）
全部批次 <- rbindlist(list(批1, 批2, 批3, 批4, 批5))
cat(sprintf("五批合计原始行数(未去重/未加总): %d\n", nrow(全部批次)))

# 关键一步：同一对(uid1, uid2)可能分散在不同批次里各出现一次(比如3月出现
# 一次、5月又出现一次)，必须先按这对人分组、把跨批次的同桌局数加总，
# 再做最终阈值筛选——不能在每批各自筛完之后才合并，那样会漏掉
# "两个月各25局、合计50局"这种真正该命中的配对
候选_同桌异常_全量 <- 全部批次[, .(总同桌局数 = sum(同桌局数)), by = .(uid1, uid2)]
cat(sprintf("跨批次加总后，共 %d 组不同的配对(已去重)\n", nrow(候选_同桌异常_全量)))

# 最终判定：总同桌局数 > 50 才算真正的候选（这才是最初业务需求定义的阈值，
# 之前每批用的>=3只是防止单批结果集过大的低门槛预筛，不是最终标准）
候选_同桌异常_最终 <- 候选_同桌异常_全量[总同桌局数 > 50][order(-总同桌局数)]
cat(sprintf("最终候选_同桌异常配对数: %d\n", nrow(候选_同桌异常_最终)))

# 存档，供后续接入customer_tier_engine.R或候选人特征表使用
fwrite(候选_同桌异常_最终, file.path(数据文件夹, "候选_同桌异常_最终版.csv"))

# 顺手看一眼Top10，直观感受一下最极端的几组配对
print(head(候选_同桌异常_最终, 10))
