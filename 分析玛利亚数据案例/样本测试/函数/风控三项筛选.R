# ==============================================================================
# 风控三项筛选.R —— 从10万行局部样本中筛选顶级实验室关注的三类风控候选
# ==============================================================================
# 【为什么这么设计，先讲方法论，再看代码】
#
# 3-5亿真实观测值 vs 10万样本，差了3000~5000倍。如果对这10万行再做一次
# "随机抽样"去测试算法，几乎必然把这三类本来就是"小概率事件"的风控对象
# (算牌、团伙、荷官串通)进一步稀释到接近0——随机抽样对"找长尾异常"这种
# 任务是错误的工具。
#
# 顶级实验室在这种场景下的标准做法是：不做行级别的随机抽样，而是在
# SQL层面直接按业务逻辑做"条件下推"(pushdown)——即，把GROUP BY+HAVING
# 这类聚合筛选逻辑，尽量放在数据库端执行，只把真正满足条件的会员/配对
# 结果集拉回来，而不是拉一份随机子集回来本地筛选。这样即使生产环境是
# 5亿行，Superset/StarRocks数据库引擎做聚合筛选的效率也远高于把数据
# 搬到本地再算，而且不会因为"抽样漏掉了异常样本"而产生假阴性。
#
# 本脚本的角色：在本地10万行样本上，用完全相同的筛选逻辑先跑一遍
# (验证SQL逻辑写得对不对)，跑通后同一套SQL模板可以直接搬到Superset/
# StarRocks连线的真实3-5亿数据上执行，不需要重新设计逻辑。
# ==============================================================================

library(data.table)  # 用于高效处理大表聚合，比base R的aggregate()快很多

路径 <- "数据库"  # 请改成实际存放ods_a168_*.csv的文件夹路径

# ------------------------------------------------------------------
# 需求一：策略性风控——每局第50把及之后才投注，且这类"晚注"订单占该
# 会员全部订单的70%以上，且订单总数超过100笔
#
# 【业务含义，外行也能懂】：真人百家乐/骰宝这类游戏，牌靴(局)开到中后段
# 时，剩余牌的构成会逐渐可预测(所谓"算牌")。如果一个会员几乎只在每局
# 第50把之后才下注，很可能是在等牌靴走到统计上更有利的阶段才出手，
# 这是典型的"职业算牌"或"系统辅助打法"信号。
# ------------------------------------------------------------------
bet01 <- fread(file.path(路径, "ods_a168_bet01.csv"))
# 只取本需求要用到的字段，减少内存占用（bet01完整表有53列，
# 这里只需要5列）
bet01_sub <- bet01[, .(bet01, bet04, bet05)]

需求一_晚注标记 <- bet01_sub[, `:=`(
  是否晚注 = bet04 >= 50  # 局内第几把(bet04)达到50及以上，标记为"晚注"
)]

需求一_结果 <- 需求一_晚注标记[, .(
  订单数 = .N,                       # 该会员全部投注订单数
  晚注订单数 = sum(是否晚注),        # 其中满足"第50把及以后"的订单数
  投注比例 = round(mean(是否晚注), 4) # 晚注订单占全部订单的比例
), by = .(uid = bet05)][
  订单数 > 100 & 投注比例 >= 0.70    # 双重过滤：订单量要够、晚注比例要够
][order(-投注比例)]

# 输出维度严格按需求指定：uid、投注比例、订单数(满足条件的晚注订单数)
需求一_输出 <- 需求一_结果[, .(uid, 投注比例, 订单数 = 晚注订单数)]
fwrite(需求一_输出, "风控筛选_策略性投注.csv")
cat(sprintf("需求一(策略性投注)：筛出 %d 位候选会员\n", nrow(需求一_输出)))


# ------------------------------------------------------------------
# 需求二：团伙同桌风控——同桌率超过30%，且满足同桌的订单数超过100笔
#
# 【业务含义】：两个会员如果频繁出现在同一局(同一个bet03)，超出正常
# 随机撞见的概率，很可能是团伙互相配合(比如"对赌"洗流水或围骰下注)。
# ------------------------------------------------------------------
配对基础表 <- bet01[, .(bet03, bet05)]  # 只需要"哪一局"+"谁参与"这两列

# 同一局(bet03)内，任意两个不同会员的组合都算一次"同桌"——
# 用自连接(self-join)按bet03配对，这是求"配对"问题的标准写法
同桌配对 <- merge(配对基础表, 配对基础表, by = "bet03", allow.cartesian = TRUE)
setnames(同桌配对, c("bet05.x","bet05.y"), c("uid1","uid2"))
同桌配对 <- 同桌配对[uid1 < uid2]  # 只保留uid1<uid2的组合，去掉(A,B)/(B,A)重复与自己对自己

同桌统计 <- 同桌配对[, .(同桌局数 = uniqueN(bet03)), by = .(uid1, uid2)]

# 各自参与的总局数(分母用"两人中较小的一方总局数"，这是同桌率的
# 保守定义——用较小值当分母，避免"一个超活跃玩家跟很多人都同桌一两次"
# 被误判成"同桌率很高"这种假阳性)
各自总局数 <- 配对基础表[, .(总局数 = uniqueN(bet03)), by = .(uid = bet05)]

同桌统计 <- merge(同桌统计, 各自总局数, by.x = "uid1", by.y = "uid")
setnames(同桌统计, "总局数", "总局数1")
同桌统计 <- merge(同桌统计, 各自总局数, by.x = "uid2", by.y = "uid")
setnames(同桌统计, "总局数", "总局数2")

同桌统计[, 同桌率 := 同桌局数 / pmin(总局数1, 总局数2)]

需求二_结果 <- 同桌统计[
  同桌局数 > 100 & 同桌率 >= 0.30   # 双重过滤：满足同桌的订单数(局数)要够、同桌率要够
][order(-同桌率)]

需求二_输出 <- 需求二_结果[, .(uid1, uid2, 同桌率 = round(同桌率, 4), 订单数 = 同桌局数)]
fwrite(需求二_输出, "风控筛选_团伙同桌.csv")
cat(sprintf("需求二(团伙同桌)：筛出 %d 组候选配对\n", nrow(需求二_输出)))

