# 【为什么要重写，不是修修补补】旧版customer_tier_engine.R用的是最早期
# "player_a/player_b/same_rate/duration_days"这套字段名——这是本项目最初
# 用来验证方法论的**合成模拟数据**的schema，跟我们后来验证过的真实a168
# 数据(bet05/bet03/bet04/eid这套编码)完全不是一回事。这次重写不是改几个
# 字段名就完事，是把整套分级逻辑，接到目前已经在1.74亿行全量数据上
# 验证过、零采样误差的真实候选数据源上：
#   - 132,982人候选特征表(投注异常+同桌异常+荷官关联三路合并)
#   - 59,833组已去重的同桌配对明细(候选_同桌异常_最终版.csv)
# ==============================================================================

library(data.table)

# ------------------------------------------------------------------
# 第一部分：读取真实数据（不是合成数据，路径请按实际本地文件调整）
# ------------------------------------------------------------------
load_real_candidate_data <- function(数据路径 = "数据库_v2_候选名单版") {
  list(
    同桌配对 = fread(file.path(数据路径, "候选_同桌异常_最终版_已去重.csv")),
    # 若您还有荷官特征、投注特征等其他真实表，一并在此读入，
    # 后续build_customer_tiers()会用到
    荷官关联 = tryCatch(fread(file.path(数据路径, "候选人特征_荷官.csv")), error = function(e) NULL),
    投注特征 = tryCatch(fread(file.path(数据路径, "候选人特征_投注.csv")), error = function(e) NULL)
  )
}

# ------------------------------------------------------------------
# 第二部分：分位数阈值计算 —— 沿用旧版"数据驱动、不硬编码"的核心原则，
# 但改用真实字段(同桌局数)，不是合成数据的same_rate/duration_days
# ------------------------------------------------------------------
compute_real_thresholds <- function(同桌配对) {
  list(
    同桌局数_p90 = quantile(同桌配对$总同桌局数, 0.90, na.rm = TRUE),
    同桌局数_p95 = quantile(同桌配对$总同桌局数, 0.95, na.rm = TRUE),
    同桌局数_p99 = quantile(同桌配对$总同桌局数, 0.99, na.rm = TRUE)
  )
}

# ------------------------------------------------------------------
# 第三部分：玩家配对维度风险分级 —— 复合相对排名法（沿用旧版已验证的
# 方法论优势：不用绝对阈值AND逻辑，因为已经证明过那会导致最高档零命中；
# 这次输入的59,833组是"已经>50局"的候选池，所以这里的分位数排名是在
# "已经算高风险候选"这个子集内部再做进一步细分，不是从全体129,000万+
# 配对里现算——这点跟旧版的语境不同，要注意区分）
# ------------------------------------------------------------------
classify_pair_tier_real <- function(同桌配对, th) {
  dt <- copy(同桌配对)
  setnames(dt, c("uid1", "uid2", "总同桌局数"))

  pctrank <- function(x) rank(x, na.last = "keep", ties.method = "average") / sum(!is.na(x))
  dt[, 同桌局数排名 := pctrank(总同桌局数)]

  dt[, tier := cut(
    同桌局数排名,
    breaks = c(-Inf, 0.50, 0.75, 0.90, 0.95, Inf),
    labels = c("一般关联", "中度关联_观察", "高度关联_待复核", "极高关联_L3高危", "极端关联_L4实锤"),
    right  = TRUE
  )]

  dt[]
}

# ------------------------------------------------------------------
# 第四部分：一次性产出，供第四部统计建模直接读取
# ------------------------------------------------------------------
build_customer_tiers_real <- function(数据路径 = "数据库_v2_候选名单版") {
  raw <- load_real_candidate_data(数据路径)
  th  <- compute_real_thresholds(raw$同桌配对)
  pair_tiers <- classify_pair_tier_real(raw$同桌配对, th)

  list(
    thresholds  = th,
    pair_tiers  = pair_tiers,
    tier_summary = pair_tiers[, .N, by = tier][order(-N)],
    荷官关联_原始 = raw$荷官关联,
    投注特征_原始 = raw$投注特征
  )
}

# 独立运行时的自检
if (sys.nframe() == 0) {
  res <- build_customer_tiers_real("数据库_v2_候选名单版")
  print(res$tier_summary)
  cat(sprintf("\n分位数阈值：P90=%.0f局 P95=%.0f局 P99=%.0f局\n",
              res$thresholds$同桌局数_p90, res$thresholds$同桌局数_p95, res$thresholds$同桌局数_p99))
}
