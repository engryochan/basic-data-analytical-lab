rnd AS (
  SELECT member_id, bet_month, round_key,
         MAX(CASE WHEN bet_side = 'Banker' THEN 1 ELSE 0 END) AS has_b,
         MAX(CASE WHEN bet_side = 'Player' THEN 1 ELSE 0 END) AS has_p,
         SUM(CASE WHEN bet_side = 'Banker' THEN stake_raw/fx ELSE 0 END) AS stk_b,
         SUM(CASE WHEN bet_side = 'Player' THEN stake_raw/fx ELSE 0 END) AS stk_p,
         SUM((payout_raw - stake_raw)/fx)                                 AS pnl_rnd
  FROM base GROUP BY member_id, bet_month, round_key
)
SELECT
  b.member_id                                                          AS member_id,
  b.bet_month                                                          AS bet_month,
  COUNT(*)                                                             AS n_orders,
  SUM(CASE WHEN b.vb_txt IS NULL THEN 1 ELSE 0 END)                    AS n_validbet_dbnull,
  SUM(CASE WHEN TRIM(COALESCE(b.vb_txt,'')) = '' THEN 1 ELSE 0 END)     AS n_validbet_blank,
  SUM(CASE WHEN b.vb_raw = 0 THEN 1 ELSE 0 END)                        AS n_validbet_true_zero,
  SUM(CASE WHEN b.vb_raw > 0 THEN 1 ELSE 0 END)                        AS n_validbet_positive,
  SUM(b.vb_raw / b.fx)                                                 AS sum_valid_bet,
  SUM(b.stake_raw / b.fx)                                              AS sum_stake,
  SUM((b.payout_raw - b.stake_raw) / b.fx)                             AS sum_game_pnl,
  SUM(b.rebate_raw / b.fx)                                             AS sum_rebate,
  SUM(CASE WHEN b.commission = '1' THEN 1 ELSE 0 END)                  AS n_no_commission,
  COUNT(DISTINCT b.round_key)                                          AS n_rounds,
  MAX(x.n_hedge_rounds)                                                AS n_hedge_rounds,
  MAX(x.n_equal_hedge)                                                 AS n_equal_hedge,
  MAX(x.n_zero_pnl_rounds)                                             AS n_zero_pnl_rounds,
  COUNT(DISTINCT b.table_id)                                           AS n_tables
FROM base b
JOIN (
  SELECT member_id, bet_month,
         SUM(CASE WHEN has_b = 1 AND has_p = 1 THEN 1 ELSE 0 END)              AS n_hedge_rounds,
         SUM(CASE WHEN has_b = 1 AND has_p = 1 AND ABS(stk_b - stk_p) < 0.005
                  THEN 1 ELSE 0 END)                                           AS n_equal_hedge,
         SUM(CASE WHEN ABS(pnl_rnd) < 0.005 THEN 1 ELSE 0 END)                 AS n_zero_pnl_rounds
  FROM rnd GROUP BY member_id, bet_month
) x ON x.member_id = b.member_id AND x.bet_month = b.bet_month
GROUP BY b.member_id, b.bet_month
ORDER BY b.member_id, b.bet_month;
