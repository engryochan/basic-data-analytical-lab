-- ── L2-1 · 真总行数（一行结果，不受任何上限影响）★ 先跑此，定分母 ──────────────
SELECT COUNT(*) AS n_total_true
FROM ods_mariadb_2b.ods_a168_bet02 b
WHERE b.dt = '2026-03-21'
  AND b.bet02 = '101';


-- ── L2-2 · 送达行数【自读】★ 本探针之核心 ───────────────────────────────────
--   施法：① 先把 Run 键旁之 LIMIT 下拉框调至【最大可选档位】，并记下它提供了哪些档位；
--         ② 跑本句；③ 把结果【拉到最底】，读【末行之 rn】—— 此数即送达之行数。
--         ④ 再点 Download to CSV，数其行数 —— 二者若不同，则前者受 DISPLAY_MAX_ROW 限、
--            后者受 SQL_MAX_ROW 限，**以 CSV 者为准**。
SELECT ROW_NUMBER() OVER (ORDER BY b.bet01) AS rn,
       b.bet01                              AS x
FROM ods_mariadb_2b.ods_a168_bet02 b
WHERE b.dt = '2026-03-21'
  AND b.bet02 = '101';


