-- 会员终身价值分级 (Customer Lifetime Value Tiering)
-- 方法论：RFM变体 —— Recency(距今活跃天数) / Frequency(活跃天数&局数) /
--         Monetary(有效投注额，盈亏字段验证通过前的最佳可用代理指标)
-- 定位：这是"价值"这一轴。风险这一轴，用报告已产出的团伙同桌/策略性投注
--       名单——两轴交叉，才是顶级电商/量化风控真正在用的"价值×风险"矩阵，
--       不是只看流水大小决定谁是VIP。
-- ============================================================================
--
-- 【诚实说明——哪些维度现在真能用，哪些还不能】
--   ✅ 已验证可用：bet12投注额、bet13有效投注额、活跃天数、最近活跃、总局数
--   🔍 待验证后可接入：真实盈亏(见同批 00_验证_aggregate_transaction盈亏字段.sql；
--      一旦跑通，把下面"真实毛利"CTE的注释打开，M_score直接改按毛利排序即可，
--      不需要重写整个框架)
--   ❌ 目前仍不可用：逐笔返水实际发放金额(现有129张表只有返水规则表，没有
--      发放流水；ROI = 毛利/投注额，同样卡在盈亏这一步，暂无法计算)
--
-- ============================================================================

WITH 会员行为基础 AS (
    SELECT
        bet05                                      AS uid,
        COUNT(DISTINCT bet03)                       AS 总局数,
        COUNT(*)                                    AS 总投注笔数,
        SUM(bet12)                                  AS 总投注额,
        SUM(bet13)                                  AS 总有效投注额,
        COUNT(DISTINCT dt)                          AS 活跃天数,
        MIN(dt)                                     AS 首次活跃日期,
        MAX(dt)                                     AS 最近活跃日期,
        DATEDIFF('2026-07-24', MAX(dt))             AS 距今未活跃天数
    FROM ods_mariadb_2b.ods_a168_bet01
    WHERE dt BETWEEN '2026-03-21' AND '2026-07-24'
    GROUP BY bet05
),

