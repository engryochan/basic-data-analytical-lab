RFM打分 AS (
    SELECT
        b.*,
        NTILE(5) OVER (ORDER BY b.距今未活跃天数 ASC)  AS R_score,   -- 越近期活跃分越高(5分最好)
        NTILE(5) OVER (ORDER BY b.活跃天数 ASC)        AS F_score,
        NTILE(5) OVER (ORDER BY b.总有效投注额 ASC)     AS M_score    -- 待真实毛利接入后，改成按毛利排
        -- 真实毛利接入后可替换为：NTILE(5) OVER (ORDER BY g.真实净盈亏 ASC) AS M_score
    FROM 会员行为基础 b
    -- 真实毛利接入后加：LEFT JOIN 真实毛利 g ON b.uid = g.uid
),

价值分级 AS (
    SELECT
        *,
        (R_score + F_score + M_score)                     AS RFM总分,
        CASE
            WHEN R_score + F_score + M_score >= 13 THEN '钻石会员'
            WHEN R_score + F_score + M_score >= 10 THEN '黄金会员'
            WHEN R_score + F_score + M_score >= 7  THEN '白银会员'
            WHEN R_score + F_score + M_score >= 4  THEN '普通会员'
            ELSE '沉睡_流失会员'
        END                                                 AS 价值分级
    FROM RFM打分
)

SELECT
    uid, 价值分级, RFM总分,
    总投注额, 总有效投注额, 总局数, 活跃天数, 距今未活跃天数,
    首次活跃日期, 最近活跃日期
FROM 价值分级
ORDER BY RFM总分 DESC;

