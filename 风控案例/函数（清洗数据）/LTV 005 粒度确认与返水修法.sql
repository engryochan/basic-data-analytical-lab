-- ============================================================================
-- 5a.【确认疑点2】dailyreport_member 是否真的"一天不止一行"
-- ============================================================================
SELECT
    行数,
    COUNT(*) AS 命中此行数的会员日组合数
FROM (
    SELECT bet05, dt, COUNT(*) AS 行数
    FROM ods_mariadb_2b.ods_a168_dailyreport_member
    WHERE dt BETWEEN '2026-03-21' AND '2026-07-24'
    GROUP BY bet05, dt
) t
GROUP BY 行数
ORDER BY 行数;
-- 如果"行数=1"占绝大多数、只有零星几个>1，那疑点2可能另有原因(比如JOIN本身放大)。
-- 如果像上一轮结果暗示的那样，大量会员日组合行数远大于1，就印证了"一天多行"。


-- ============================================================================
-- 5b.【找规律】挑一个重复很多次的会员日，把所有字段摊开，找时间戳/自增ID/
--    版本号——用来判断"哪一行才是当天最终值"（是取最大的、最新的，还是别的规则）
-- ============================================================================
SELECT *
FROM ods_mariadb_2b.ods_a168_dailyreport_member
WHERE bet05 = '103517820' AND dt = '2026-07-17';
-- 把结果整表贴回来即可，不用先猜是哪一列——列名和实际值一起看，
-- 才能确定该按什么排序取"最终那一行"，或者是否应该在某个更细的
-- 维度(比如游戏/产品)上分别取最终值再相加，而不是整天只留一行。


